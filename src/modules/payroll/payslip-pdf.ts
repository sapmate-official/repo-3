export interface PayslipPdfParams {
  payslipId: string;
  orgName: string;
  employeeName: string;
  employeeEmail: string;
  monthName: string;
  year: number;
  workingDays: number;
  presentDays: number;
  lopDays: number;
  grossEarnings: number;
  totalDeductions: number;
  netPay: number;
  lineItems: { componentCode: string; category: string; finalAmount: number }[];
}

export function createPayslipPdfBuffer(params: PayslipPdfParams): Buffer {
  const sanitize = (text: string): string => text.replace(/[()\\]/g, '');

  const lines = [
    `BT /F1 20 Tf 50 740 Td (PAYSLIP - ${params.monthName.toUpperCase()} ${params.year}) Tj ET`,
    `BT /F1 12 Tf 50 715 Td (${sanitize(params.orgName)}) Tj ET`,
    `BT /F1 10 Tf 50 685 Td (Employee: ${sanitize(params.employeeName)} <${sanitize(params.employeeEmail)}>) Tj ET`,
    `BT /F1 10 Tf 50 670 Td (Working Days: ${params.workingDays} | Present: ${params.presentDays} | LOP Days: ${params.lopDays}) Tj ET`,
    `BT /F1 12 Tf 50 635 Td (EARNINGS) Tj ET`
  ];

  let currentY = 615;
  const earnings = params.lineItems.filter((i) => i.category === 'EARNING');
  for (const item of earnings) {
    lines.push(`BT /F1 10 Tf 60 ${currentY} Td (${sanitize(item.componentCode)}: $${item.finalAmount.toFixed(2)}) Tj ET`);
    currentY -= 15;
  }
  lines.push(`BT /F1 10 Tf 60 ${currentY} Td (Gross Earnings: $${params.grossEarnings.toFixed(2)}) Tj ET`);
  currentY -= 25;

  lines.push(`BT /F1 12 Tf 50 ${currentY} Td (DEDUCTIONS) Tj ET`);
  currentY -= 20;

  const deductions = params.lineItems.filter((i) => i.category === 'DEDUCTION');
  for (const item of deductions) {
    lines.push(`BT /F1 10 Tf 60 ${currentY} Td (${sanitize(item.componentCode)}: $${item.finalAmount.toFixed(2)}) Tj ET`);
    currentY -= 15;
  }
  lines.push(`BT /F1 10 Tf 60 ${currentY} Td (Total Deductions: $${params.totalDeductions.toFixed(2)}) Tj ET`);
  currentY -= 30;

  lines.push(`BT /F1 14 Tf 50 ${currentY} Td (NET PAYABLE: $${params.netPay.toFixed(2)}) Tj ET`);
  currentY -= 30;
  lines.push(`BT /F1 8 Tf 50 ${currentY} Td (Confidential. Generated by Alkaa Workforce OS.) Tj ET`);

  const contentStream = lines.join('\n');
  const streamLength = Buffer.byteLength(contentStream, 'utf-8');

  const obj1 = '1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n';
  const obj2 = '2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n';
  const obj3 = '3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources << /Font << /F1 5 0 R >> >> >>\nendobj\n';
  const obj4 = `4 0 obj\n<< /Length ${streamLength} >>\nstream\n${contentStream}\nendstream\nendobj\n`;
  const obj5 = '5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n';

  const header = '%PDF-1.4\n';
  const offset0 = 0;
  const offset1 = Buffer.byteLength(header, 'utf-8');
  const offset2 = offset1 + Buffer.byteLength(obj1, 'utf-8');
  const offset3 = offset2 + Buffer.byteLength(obj2, 'utf-8');
  const offset4 = offset3 + Buffer.byteLength(obj3, 'utf-8');
  const offset5 = offset4 + Buffer.byteLength(obj4, 'utf-8');

  const pad = (n: number) => n.toString().padStart(10, '0');
  const startXref = offset5 + Buffer.byteLength(obj5, 'utf-8');

  const xref = [
    'xref',
    '0 6',
    `${pad(offset0)} 65535 f `,
    `${pad(offset1)} 00000 n `,
    `${pad(offset2)} 00000 n `,
    `${pad(offset3)} 00000 n `,
    `${pad(offset4)} 00000 n `,
    `${pad(offset5)} 00000 n `,
    'trailer',
    '<< /Size 6 /Root 1 0 R >>',
    'startxref',
    startXref.toString(),
    '%%EOF'
  ].join('\n');

  return Buffer.from(`${header}${obj1}${obj2}${obj3}${obj4}${obj5}${xref}`, 'utf-8');
}
